<?php
/**
 * Обработка текстов каталога на выдаче (без изменения данных в БД).
 */
if (!function_exists('mf_catalog_strip_stock_disclaimer'))
{
	/**
	 * Удаляет служебную фразу из краткого/полного описания товара.
	 */
	function mf_catalog_strip_stock_disclaimer(string $html): string
	{
		if ($html === '')
		{
			return $html;
		}

		$out = $html;

		// Одна строка / один абзац: гибкие пробелы (в т.ч. неразрывный U+00A0).
		$re = '~В[\s\x{00A0}]+наличии[\s\x{00A0}]+на[\s\x{00A0}]+складе\.[\s\x{00A0}]*Наличие[\s\x{00A0}]+и[\s\x{00A0}]+стоимость[\s\x{00A0}]+уточняйте\.?~u';
		$out = preg_replace($re, '', $out) ?? $out;

		// Два предложения разнесены тегами (<br> или два <p>).
		$re2 = '~В[\s\x{00A0}]+наличии[\s\x{00A0}]+на[\s\x{00A0}]+складе\.(?:\s*</p>\s*<p[^>]*>\s*|\s*<br\s*/?>\s*)+Наличие[\s\x{00A0}]+и[\s\x{00A0}]+стоимость[\s\x{00A0}]+уточняйте\.?~iu';
		$out = preg_replace($re2, '', $out) ?? $out;

		// Точное совпадение без учёта регистра (на случай правок в источнике).
		foreach (['В наличии на складе. Наличие и стоимость уточняйте.', 'В наличии на складе. Наличие и стоимость уточняйте'] as $literal)
		{
			$out = str_ireplace($literal, '', $out);
		}

		// Пустые абзацы после вырезания.
		$out = preg_replace('~<p[^>]*>\s*(<br\s*/?>|\s|&nbsp;|\x{00A0})*\s*</p>~iu', '', $out) ?? $out;
		$out = preg_replace('~(?:\s|&nbsp;|\x{00A0}){3,}~u', ' ', $out) ?? $out;

		return trim($out);
	}
}
